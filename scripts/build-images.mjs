// Builds responsive AVIF + WebP derivatives from the photographs extracted
// from the project PDFs (assets/source/*.jpg) and writes a typed manifest.
//
//   npm run images
//
// Source images are never upscaled: widths larger than the original are skipped.

import { readdir, mkdir, readFile, writeFile, stat } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..");
const SRC = path.join(ROOT, "assets/source");
const OUT = path.join(ROOT, "public/img");
const MANIFEST = path.join(ROOT, "src/content/images.generated.ts");
const OG = path.join(ROOT, "public/og");
const MARK = path.join(ROOT, "public/qis-mark.svg");

const TARGET_WIDTHS = [480, 800];
const AVIF = { quality: 52, effort: 6 };
const WEBP = { quality: 76, effort: 5 };

async function exists(file) {
  try {
    await stat(file);
    return true;
  } catch {
    return false;
  }
}

const toHex = (n) => n.toString(16).padStart(2, "0");

async function processImage(file) {
  const id = path.basename(file, ".jpg");
  const input = sharp(path.join(SRC, file));
  const { width, height } = await input.metadata();
  const { dominant } = await input.stats();

  const widths = [...TARGET_WIDTHS.filter((w) => w < width - 40), width];

  for (const w of widths) {
    const base = path.join(OUT, `${id}-${w}`);
    const resized = () => sharp(path.join(SRC, file)).resize({ width: w });
    if (!(await exists(`${base}.avif`))) await resized().avif(AVIF).toFile(`${base}.avif`);
    if (!(await exists(`${base}.webp`))) await resized().webp(WEBP).toFile(`${base}.webp`);
  }

  return {
    id,
    width,
    height,
    widths,
    color: `#${toHex(dominant.r)}${toHex(dominant.g)}${toHex(dominant.b)}`,
  };
}

// Social preview (Open Graph) image: a 1200×630 crop with the monogram
// set small in the lower-left corner over a soft shade.
async function buildOg(file, markSvg) {
  const id = path.basename(file, ".jpg");
  const out = path.join(OG, `${id}.jpg`);
  if (await exists(out)) return;
  const W = 1200;
  const H = 630;
  const shade = Buffer.from(
    `<svg width="${W}" height="${H}"><defs><linearGradient id="g" x1="0" y1="0" x2="0" y2="1"><stop offset="0.6" stop-color="#1e1b17" stop-opacity="0"/><stop offset="1" stop-color="#1e1b17" stop-opacity="0.45"/></linearGradient></defs><rect width="${W}" height="${H}" fill="url(#g)"/></svg>`,
  );
  const mark = await sharp(Buffer.from(markSvg.replace('fill="#1e1b17"', 'fill="#f3efe7"')))
    .resize({ height: 40 })
    .png()
    .toBuffer();
  await sharp(path.join(SRC, file))
    .resize(W, H, { fit: "cover", position: "attention" })
    .composite([
      { input: shade, top: 0, left: 0 },
      { input: mark, left: 56, top: H - 56 - 40 },
    ])
    .jpeg({ quality: 82, mozjpeg: true })
    .toFile(out);
}

await mkdir(OUT, { recursive: true });
await mkdir(OG, { recursive: true });
const files = (await readdir(SRC)).filter((f) => f.endsWith(".jpg")).sort();
const entries = await Promise.all(files.map(processImage));
const markSvg = await readFile(MARK, "utf8");
await Promise.all(files.map((f) => buildOg(f, markSvg)));

const body = entries
  .map(
    (e) =>
      `  "${e.id}": { width: ${e.width}, height: ${e.height}, widths: [${e.widths.join(", ")}], color: "${e.color}" },`,
  )
  .join("\n");

await writeFile(
  MANIFEST,
  `// Generated by scripts/build-images.mjs — do not edit by hand.\n\nexport const imageManifest = {\n${body}\n} as const;\n\nexport type ImageId = keyof typeof imageManifest;\n`,
);

console.log(`Processed ${entries.length} images → public/img (+ social previews in public/og), manifest → src/content/images.generated.ts`);
